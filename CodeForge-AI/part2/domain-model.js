function getRoleOrThrow(roleId) {
  const role = ROLES[roleId];
  if (!role) throw new Error(`Unknown roleId: ${roleId}`);
  return role;
}

// Strips answer keys / hidden expectations before a task would ever be sent
// to a client. Deterministic scoring always runs against the full TASKS
// object server-side — only the sanitized view goes over the wire.
function sanitizeTaskForClient(task) {
  const { correctIndex, aiRubric, sqlChecks, prerequisiteCheckTaskId, ...rest } = task;
  const out = { ...rest };
  if (task.testCases) {
    out.testCases = task.testCases.map((tc) =>
      tc.hidden ? { args: tc.args, hidden: true } : { args: tc.args, expected: tc.expected }
    );
  }
  return out;
}

